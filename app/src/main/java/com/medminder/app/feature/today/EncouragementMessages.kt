    fun indexForTime(instant: Instant, zoneId: ZoneId): Int {
        val localDateTime = instant.atZone(zoneId)
        val hourlySlot = (localDateTime.toLocalDate().toEpochDay() * HOURS_IN_DAY) + localDateTime.hour
        return Math.floorMod(hourlySlot, displayMessages.size.toLong()).toInt()
    }

